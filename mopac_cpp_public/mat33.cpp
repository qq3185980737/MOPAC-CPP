// mat33.cpp
#include "mat33.h"
void mat33(const double* a, const double* b, double* c) {
    double t[9];
    t[0]=b[0]*a[0]+b[1]*a[3]+b[2]*a[6];
    t[1]=b[0]*a[1]+b[1]*a[4]+b[2]*a[7];
    t[2]=b[0]*a[2]+b[1]*a[5]+b[2]*a[8];
    t[3]=b[3]*a[0]+b[4]*a[3]+b[5]*a[6];
    t[4]=b[3]*a[1]+b[4]*a[4]+b[5]*a[7];
    t[5]=b[3]*a[2]+b[4]*a[5]+b[5]*a[8];
    t[6]=b[6]*a[0]+b[7]*a[3]+b[8]*a[6];
    t[7]=b[6]*a[1]+b[7]*a[4]+b[8]*a[7];
    t[8]=b[6]*a[2]+b[7]*a[5]+b[8]*a[8];
    c[0]=a[0]*t[0]+a[3]*t[3]+a[6]*t[6];
    c[1]=a[0]*t[1]+a[3]*t[4]+a[6]*t[7];
    c[2]=a[0]*t[2]+a[3]*t[5]+a[6]*t[8];
    c[3]=a[1]*t[0]+a[4]*t[3]+a[7]*t[6];
    c[4]=a[1]*t[1]+a[4]*t[4]+a[7]*t[7];
    c[5]=a[1]*t[2]+a[4]*t[5]+a[7]*t[8];
    c[6]=a[2]*t[0]+a[5]*t[3]+a[8]*t[6];
    c[7]=a[2]*t[1]+a[5]*t[4]+a[8]*t[7];
    c[8]=a[2]*t[2]+a[5]*t[5]+a[8]*t[8];
}
